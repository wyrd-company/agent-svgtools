#!/usr/bin/env bash
#
# Generate the agent-svgtools Homebrew formula from the built release artifacts,
# commit it to a checked-out tap repository, and push.
#
# Expected environment (set by .github/workflows/cd.yml):
#   ARTIFACT_ROOT  directory holding agent-svgtools-<version>-<target>.tar.gz[.sha256]
#   TAG            the pushed git tag (bare SemVer, no "v" prefix)
#   VERSION        the version parsed from the tag
#   REPOSITORY     owner/repo of this project (e.g. wyrd-company/agent-trace)
#   TAP_DIR        path to the checked-out tap repository
set -euo pipefail

: "${ARTIFACT_ROOT:?ARTIFACT_ROOT is required}"
: "${TAG:?TAG is required}"
: "${VERSION:?VERSION is required}"
: "${REPOSITORY:?REPOSITORY is required}"
: "${TAP_DIR:?TAP_DIR is required}"

base_url="https://github.com/${REPOSITORY}/releases/download/${TAG}"

# Read the sha256 for a given target's tarball from its sidecar file.
sha_for() {
  local target="$1"
  local sha_file="${ARTIFACT_ROOT}/agent-svgtools-${VERSION}-${target}.tar.gz.sha256"
  if [[ ! -f "$sha_file" ]]; then
    echo "missing checksum: $sha_file" >&2
    exit 1
  fi
  awk '{print $1; exit}' "$sha_file"
}

url_for() {
  echo "${base_url}/agent-svgtools-${VERSION}-$1.tar.gz"
}

mac_arm="aarch64-apple-darwin"
mac_x86="x86_64-apple-darwin"
linux_arm="aarch64-unknown-linux-musl"
linux_x86="x86_64-unknown-linux-musl"

formula_dir="${TAP_DIR}/Formula"
mkdir -p "$formula_dir"
formula="${formula_dir}/agent-svgtools.rb"

cat >"$formula" <<EOF
# This file is generated by scripts/publish-homebrew-tap.sh. Do not edit.
class AgentSvgtools < Formula
  desc "Machine-first CLI scoring AI-authored SVGs against raster references"
  homepage "https://github.com/${REPOSITORY}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$(url_for "$mac_arm")"
      sha256 "$(sha_for "$mac_arm")"
    end
    on_intel do
      url "$(url_for "$mac_x86")"
      sha256 "$(sha_for "$mac_x86")"
    end
  end

  on_linux do
    on_arm do
      url "$(url_for "$linux_arm")"
      sha256 "$(sha_for "$linux_arm")"
    end
    on_intel do
      url "$(url_for "$linux_x86")"
      sha256 "$(sha_for "$linux_x86")"
    end
  end

  def install
    bin.install "agent-svgtools"
  end

  test do
    assert_match "agent-svgtools", shell_output("#{bin}/agent-svgtools --version")
  end
end
EOF

echo "Generated formula:"
cat "$formula"

cd "$TAP_DIR"
git config user.name "github-actions[bot]"
git config user.email "github-actions[bot]@users.noreply.github.com"
git add "Formula/agent-svgtools.rb"
if git diff --cached --quiet; then
  echo "Formula unchanged; nothing to commit."
  exit 0
fi
git commit -m "agent-svgtools ${VERSION}"
git push origin HEAD
